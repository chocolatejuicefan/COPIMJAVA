public class stringOperations {
public static void main(String[] args) {
        String school = "Florida International University";
        System.out.println(school);
        System.out.println(school.length());
        System.out.println(school.toUpperCase());
        System.out.println(school.toLowerCase());
        System.out.println(school.charAt(7));
        System.out.println(school.replace('i', 'I'));
        System.out.println(school);
        System.out.println(school.equals("florida international university"));
    }
}
